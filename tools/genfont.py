"""Generate a 1-bit bitmap font (ASCII + Ukrainian Cyrillic) as C source.
Usage: genfont.py <ttf> <px> <out.c> [preview.png]
Default font: Terminus (TTF) 12 px, SIL OFL 1.1 (https://files.ax86.net/terminus-ttf/)."""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, px, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
preview = sys.argv[4] if len(sys.argv) > 4 else None
chars = [chr(c) for c in range(0x20, 0x7f)]
chars += [chr(c) for c in range(0x410, 0x450)]          # А..я
chars += list("ЄІЇҐєіїґ°…—–«»’№")
# Hand-drawn replacements: (char, px) -> (first row, rows). Terminus draws Cyrillic 'д' like Latin 'g'.
OVERRIDES = {
    ('д', 12): (4, ['..###.', '.#..#.', '.#..#.', '.#..#.', '.#..#.', '######', '#....#']),
}
font = ImageFont.truetype(ttf, px)
asc, desc = font.getmetrics()
H = asc + desc
glyphs = []
for ch in chars:
    l, t, r, b = font.getbbox(ch)
    adv = max(1, round(font.getlength(ch)))
    w = max(adv, r)
    img = Image.new('L', (w + 1, H), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    bits = [[1 if img.getpixel((x, y)) > 110 else 0 for x in range(w)] for y in range(H)]
    ov = OVERRIDES.get((ch, px))
    if ov and 'Terminus' in ttf:
        top0, rows = ov
        for y in range(H):
            for x in range(w):
                r = y - top0
                bits[y][x] = 1 if 0 <= r < len(rows) and x < len(rows[r]) and rows[r][x] == '#' else 0
    # trim empty right columns beyond advance
    glyphs.append((ch, adv, w, bits))

# crop to the union of inked rows so 3 lines fit into 32 px
rows = [y for _, _, _, bits in glyphs for y in range(H) if any(bits[y])]
top, bot = min(rows), max(rows)
glyphs = [(ch, adv, w, bits[top:bot + 1]) for ch, adv, w, bits in glyphs]
asc -= top
H = bot - top + 1

def emit():
    lines = ['/* generated by tools/genfont.py from %s @%dpx */' % (ttf.split('/')[-1], px),
             '#include "font.h"', '']
    data = []
    entries = []
    for ch, adv, w, bits in glyphs:
        off = len(data)
        # column-major, each column = H bits packed into ceil(H/8) bytes, LSB = top
        nb = (H + 7) // 8
        for x in range(w):
            col = 0
            for y in range(H):
                if bits[y][x]:
                    col |= 1 << y
            for k in range(nb):
                data.append((col >> (8 * k)) & 0xff)
        entries.append((ord(ch), adv, w, off))
    lines.append('static const uint8_t font_data[] = {')
    for i in range(0, len(data), 16):
        lines.append('\t' + ', '.join('0x%02x' % v for v in data[i:i + 16]) + ',')
    lines.append('};')
    lines.append('static const struct font_glyph font_glyphs[] = {')
    for cp, adv, w, off in sorted(entries):
        lines.append('\t{0x%04x, %d, %d, %d},' % (cp, adv, w, off))
    lines.append('};')
    lines.append('const struct font font_main = { %d, %d, font_glyphs, %d, font_data };' % (H, asc, len(entries)))
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('height', H, 'glyphs', len(entries), 'bytes', len(data))

emit()
if preview:
    sample = ["Кухня: світло ВКЛ  23.4°", "🔔 Дзвонять! Ґанок їжа Є", "Батарея 87% · 437 W"]
    S = 4
    img = Image.new('1', (128, 32), 0)
    gm = {g[0]: g for g in glyphs}
    y = 0
    for line in sample:
        x = 0
        for ch in line:
            g = gm.get(ch, gm['?'])
            for xx in range(g[2]):
                for yy in range(H):
                    if g[3][yy][xx] and x + xx < 128 and y + yy < 32:
                        img.putpixel((x + xx, y + yy), 1)
            x += g[1]
        y += H
    img.resize((128 * S, 32 * S), Image.NEAREST).save(preview)
